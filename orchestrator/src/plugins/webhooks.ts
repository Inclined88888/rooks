/**
 * Signed incoming webhooks of plugins, third-party ones included.
 *
 * A plugin declares `webhooks: [{ name, auth }]` in its manifest — `auth` is
 * one of the signature formats shipped in `webhook-formats.ts` (`standard`,
 * `github`, `stripe`, `slack`…) — and subscribes with
 * `ctx.webhooks.on(name, handler)`. A remote service then calls
 * `POST /api/plugins/hooks/<slug>/<name>` with no session at all — `<slug>`
 * is the plugin id without `@`, `/` turned into `-` (`webhook-path.ts`).
 *
 * Everything that makes such a call trustworthy is done HERE, by the host,
 * before a line of the plugin runs — the same front, replay guard and rate
 * limits as the native trigger webhooks (`triggers/webhook.ts`); `standard`
 * keeps their exact verifier, every other format goes through the generic
 * engine (`webhook-schemes.ts`). A plugin author cannot get any of it wrong.
 *
 * Order: IP rate limit → bounded raw body → handler and secret → signature
 * (current secret, then the previous one during a rotation) → owner identity
 * → route rate limit → replay guard → handler. An unknown plugin, a disabled
 * one, an undeclared or unsubscribed name, a webhook with no secret yet and a
 * bad signature all get the same 401: no oracle on what is installed.
 *
 * The secret is generated by the host (shown once, to the superadmin who
 * generated it) or, for a service that makes its own (Stripe, Slack, a
 * Discord public key…), pasted by a superadmin and never shown again. Either
 * way it is sealed with the vault envelope in `plugin_kv` under a
 * `@settings/` key — so the vault's witness choice and `rekeyVault` cover it.
 * A new secret keeps the old one valid for `ROTATION_GRACE_MS`, so the sender
 * can be switched without losing calls — except when the format changed:
 * the record names its format, a secret of another format never verifies,
 * and replacing it drops the old one at once.
 *
 * The record also names the package it was set for (`publisher`: npm name and
 * trust — built in, signed, unsigned). `rooks plugin remove` forgets the
 * secrets, but a plugin can vanish otherwise (folder deleted, `npm
 * uninstall`); a package installed later under the same id from another npm
 * name, or with another trust, then finds a record that is not its own: it is
 * refused like a secret of another format (401, `needsRegeneration`). One
 * exception: the signed release of an unsigned copy keeps its secret.
 *
 * The handler runs inside the identity of the account that generated the
 * secret (`integrationRequestIdentity`: its own data, never `:all`), or as the
 * plugin's own job when no account exists yet — never as an anonymous
 * caller. Its TO DO writes carry `origin: { kind: 'plugin', id }`.
 */
