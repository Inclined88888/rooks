/**
 * The package a secret was set for. The npm name: another author cannot
 * publish under it on the registry. The trust: a signed package whose id is
 * taken over by an unsigned copy is not the same plugin (the reverse is an
 * update, `signsUnsignedPublisher`).
 * Not the signing key: every key is the product's own, and rotating it must
 * not break every webhook.
 */
export type PluginWebhookPublisher = { pkg: string; trust: 'builtin' | 'signed' | 'unsigned' };

/** The publisher of a plugin as the loader lists it. */
export function webhookPublisherOf(status: { pkg: string; signed: boolean; builtin?: true }): PluginWebhookPublisher {
  return { pkg: status.pkg, trust: status.signed ? 'signed' : status.builtin ? 'builtin' : 'unsigned' };
}

/**
 * The signed (or built-in) release of an unsigned copy of its own name: only
 * the holder of the product's keys can produce it, so the secret follows it, as
 * the plugin's data does (`keepsPluginData`). Never the reverse.
 */
const signsUnsignedPublisher = (bound: PluginWebhookPublisher, incoming: PluginWebhookPublisher): boolean =>
  bound.pkg === incoming.pkg && bound.trust === 'unsigned' && incoming.trust !== 'unsigned';

/** Does the secret set for `bound` verify calls for `incoming`? */
const samePublisher = (bound: PluginWebhookPublisher | null, incoming: PluginWebhookPublisher | null): boolean =>
  bound !== null && incoming !== null
  && ((bound.pkg === incoming.pkg && bound.trust === incoming.trust) || signsUnsignedPublisher(bound, incoming));

type Registration = {
  pluginId: string;
  handler: PluginWebhookHandler;
  auth: WebhookFormatId;
  /** `null` on a test host that does not say: a bound record then never verifies. */
  publisher: PluginWebhookPublisher | null;
};
/** Keyed by `<slug>/<name>`: what the public path names. */
const handlers = new Map<string, Registration>();
const handlerKey = (slug: string, name: string) => `${slug}/${name}`;

/**
 * One handler per declared name. The returned disposer is wired to the
 * plugin's lifecycle by the facade: an unloaded plugin answers like an
 * unknown one. A slug belongs to one plugin: another id giving the same slug
 * (`@acme/x` and `acme-x`) is refused while the first one is registered.
 * A record older than publishers is bound here to the package that loads.
 */
export function registerPluginWebhook(
  pluginId: string,
  name: string,
  handler: PluginWebhookHandler,
  auth: WebhookFormatId = 'standard',
  publisher: PluginWebhookPublisher | null = null,
): () => void {
  const slug = pluginHookSlug(pluginId);
  if (!slug) throw new Error(`plugin \`${pluginId}\`: its id gives no webhook slug ([a-z0-9-] only)`);
  for (const [key, held] of handlers) {
    if (key.startsWith(handlerKey(slug, '')) && held.pluginId !== pluginId) {
      throw new Error(`plugin \`${pluginId}\`: webhook slug \`${slug}\` is already used by plugin \`${held.pluginId}\``);
    }
  }
  const key = handlerKey(slug, name);
  if (handlers.has(key)) throw new Error(`plugin \`${pluginId}\`: webhook \`${name}\` already has a handler`);
  // A fresh object, so a disposer only ever removes its own registration.
  if (!webhookFormat(auth)) throw new Error(`plugin \`${pluginId}\`: webhook \`${name}\` names an unknown format \`${auth}\``);
  const entry: Registration = { pluginId, handler, auth, publisher };
  handlers.set(key, entry);
  if (publisher) adoptLegacyRecord(pluginId, name, publisher);
  return () => { if (handlers.get(key) === entry) handlers.delete(key); };
}

export function pluginWebhookListening(pluginId: string, name: string): boolean {
  const slug = pluginHookSlug(pluginId);
  return slug !== null && handlers.get(handlerKey(slug, name))?.pluginId === pluginId;
}

/** Thrown when a request (someone's identity) asks to act as a webhook's owner. */
export class PluginWebhookOwnerError extends Error {}

/**
 * Runs `fn` exactly as a delivery of webhook `name` would: as the account that
 * generated its secret, unattended, TO DO writes stamped with the plugin's
 * origin. It sees no more than an incoming call sees, so a plugin can finish
 * at start what only a delivery could do (a connector's data migration)
 * without waiting for the service to call. Refused inside a request: the
 * route of user B must never act as user A. No handler, no usable secret or
 * an owner who lost the plugin: nothing runs, the reason is returned.
 */
export async function runAsPluginWebhookOwner<T>(
  pluginId: string,
  name: string,
  fn: () => T | Promise<T>,
  where = `[plugin-hooks] ${pluginId}/${name}`,
): Promise<PluginWebhookOwnerRun<T>> {
  if (inPluginRequest()) {
    throw new PluginWebhookOwnerError(`plugin \`${pluginId}\`: webhooks.asOwner cannot run inside a request or a delivery`);
  }
  const slug = pluginHookSlug(pluginId);
  const registration = slug ? handlers.get(handlerKey(slug, name)) : undefined;
  if (!registration || registration.pluginId !== pluginId) return { ran: false, reason: 'not_listening' };
  const record = recordFor(registration, name, where);
  if (!record) return { ran: false, reason: 'no_secret' };
  let identity: ReturnType<typeof integrationRequestIdentity>;
  try {
    identity = integrationRequestIdentity(pluginId, record.ownerUserId ?? `plugin:${pluginId}`);
  } catch {
    return { ran: false, reason: 'owner_unavailable' };
  }
  const value = await runPluginRequest(identity, () => withTodoOrigin({ kind: 'plugin', id: pluginId }, fn));
  return { ran: true, value };
}

