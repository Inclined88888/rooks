/** `plugin_kv` namespace of the records: no manifest id can take it. */
export const PLUGIN_WEBHOOK_STORE = '@rooks/plugin-webhooks';
/** How long the replaced secret keeps verifying after a regeneration. */
export const ROTATION_GRACE_MS = 24 * 3600_000;

const PublisherSchema = z.object({ pkg: z.string().min(1), trust: z.enum(['builtin', 'signed', 'unsigned']) });

const RecordSchema = z.object({
  /** The format the secret was made for; records older than formats are `standard`. */
  scheme: z.string().min(1).default('standard'),
  /** Who made the secret: the host (`generated`) or the sending service (`provided`). */
  source: z.enum(['generated', 'provided']).default('generated'),
  current: z.string().min(1),
  previous: z.string().min(1).nullable(),
  previousUntil: z.number().nullable(),
  ownerUserId: z.string().nullable(),
  /** The package the secret was set for; `null` on a record older than this field. */
  publisher: PublisherSchema.nullable().default(null),
  createdAt: z.number(),
  rotatedAt: z.number(),
});
type WebhookRecord = z.infer<typeof RecordSchema>;

const recordKey = (pluginId: string, name: string) => `@settings/${pluginId}/${name}`;
const recordIdentity = (pluginId: string, name: string) => pluginKvIdentity(PLUGIN_WEBHOOK_STORE, recordKey(pluginId, name));

function readRecord(pluginId: string, name: string): WebhookRecord | null {
  const raw = dbApi.pluginKvGet(PLUGIN_WEBHOOK_STORE, recordKey(pluginId, name));
  if (raw === undefined) return null;
  const parsed = RecordSchema.safeParse(JSON.parse(openWithVault(raw, recordIdentity(pluginId, name))));
  return parsed.success ? parsed.data : null;
}

function writeRecord(pluginId: string, name: string, record: WebhookRecord): void {
  dbApi.pluginKvSet(PLUGIN_WEBHOOK_STORE, recordKey(pluginId, name),
    sealWithVault(JSON.stringify(record), recordIdentity(pluginId, name)));
}

/**
 * Binds a record written before publishers existed to the plugin loading it
 * now: the package installed when the daemon upgrades is the one the secret
 * was made for, short of a removal by hand in between. Rebinds only a secret
 * set for an unsigned copy to the signed release taking it over: an unsigned
 * copy coming back afterwards must not verify with it.
 */
function adoptLegacyRecord(pluginId: string, name: string, publisher: PluginWebhookPublisher): void {
  try {
    const record = readRecord(pluginId, name);
    if (record && (record.publisher === null || signsUnsignedPublisher(record.publisher, publisher))) {
      writeRecord(pluginId, name, { ...record, publisher });
    }
  } catch (err) {
    // A locked vault: the call path refuses an unreadable record anyway.
    console.warn(`[plugin-hooks] ${pluginId}/${name}: secret not bound to its package — ${(err as Error).message}`);
  }
}

/** Why a stored secret no longer verifies, `null` when it does. */
function staleReason(record: WebhookRecord, auth: WebhookFormatId, publisher: PluginWebhookPublisher | null): 'format' | 'publisher' | null {
  if (record.scheme !== auth) return 'format';
  if (record.publisher !== null && !samePublisher(record.publisher, publisher)) return 'publisher';
  return null;
}

/** What the management routes may show. Never a secret. */
export type PluginWebhookStatus = {
  name: string;
  auth: WebhookFormatId;
  /** The format's name, `GitHub`. */
  label: string;
  /** What the format protects against, see `WebhookSchemeLevel`. */
  level: WebhookSchemeLevel;
  /** The ways a secret can be set: generated here, pasted from the service, or both. */
  secretSources: Array<'generated' | 'provided'>;
  /** `public-key` for a format verified by the service's public key (Discord). */
  secretKind: 'secret' | 'public-key';
  /** The stored secret was made for another format or package: nothing verifies until a new one is set. */
  needsRegeneration: boolean;
  /** Why, when `needsRegeneration`: the plugin changed its format, or another package took its id. */
  regenerationReason: 'format' | 'publisher' | null;
  /** Same path on the app (relay) and on the daemon. */
  path: string;
  configured: boolean;
  /** The plugin subscribed this name and is loaded. */
  listening: boolean;
  /** Until when the replaced secret still verifies; `null` outside a rotation. */
  previousUntil: number | null;
  rotatedAt: number | null;
  /** The account the handler acts as; `null` = the plugin's own job. */
  owner: { id: string; name: string } | null;
};

function formatOrThrow(auth: WebhookFormatId): WebhookFormat {
  const format = webhookFormat(auth);
  if (!format) throw new Error(`unknown webhook format \`${auth}\``);
  return format;
}

function secretSourcesOf(format: WebhookFormat): Array<'generated' | 'provided'> {
  return format.scheme.kind === 'ed25519' ? ['provided'] : [...format.scheme.secret.sources];
}

export function pluginWebhookStatus(
  pluginId: string,
  name: string,
  auth: WebhookFormatId = 'standard',
  publisher: PluginWebhookPublisher | null = null,
  now: number = Date.now(),
): PluginWebhookStatus {
  const format = formatOrThrow(auth);
  const record = readRecord(pluginId, name);
  const stale = record ? staleReason(record, auth, publisher) : null;
  const ownerRow = record?.ownerUserId ? dbApi.getUserById(record.ownerUserId) : undefined;
  return {
    name,
    auth,
    label: format.label,
    level: format.level,
    secretSources: secretSourcesOf(format),
    secretKind: format.scheme.kind === 'ed25519' ? 'public-key' : 'secret',
    needsRegeneration: stale !== null,
    regenerationReason: stale,
    path: pluginHookPath(pluginId, name),
    configured: record !== null,
    listening: pluginWebhookListening(pluginId, name),
    previousUntil: record?.previous && record.previousUntil !== null && record.previousUntil > now ? record.previousUntil : null,
    rotatedAt: record?.rotatedAt ?? null,
    owner: ownerRow ? { id: ownerRow.id, name: ownerRow.name } : null,
  };
}

/** Refusal of a secret operation the format does not allow; its message names no value. */
export class PluginWebhookSecretError extends Error {}

type RotateOptions = { keepPrevious?: boolean; now?: number };

function storeSecret(
  pluginId: string,
  name: string,
  auth: WebhookFormatId,
  source: 'generated' | 'provided',
  secret: string,
  ownerUserId: string | null,
  publisher: PluginWebhookPublisher,
  opts: RotateOptions,
): void {
  const now = opts.now ?? Date.now();
  const old = readRecord(pluginId, name);
  // A secret of another format, or set for another package, verifies nothing
  // here: keeping it "valid" for 24 h would hand the new package the old
  // sender's calls.
  const keep = old !== null && staleReason(old, auth, publisher) === null && opts.keepPrevious !== false;
  writeRecord(pluginId, name, {
    scheme: auth,
    source,
    current: secret,
    previous: keep ? old.current : null,
    previousUntil: keep ? now + ROTATION_GRACE_MS : null,
    ownerUserId,
    publisher,
    createdAt: old?.createdAt ?? now,
    rotatedAt: now,
  });
}

/**
 * New secret for the webhook, returned ONCE. The replaced one stays valid
 * for `ROTATION_GRACE_MS`, unless `keepPrevious` is false (a leaked secret)
 * or it was made for another format or package. `ownerUserId` becomes the
 * identity the handler runs under; `publisher`, the only package it verifies
 * for. Refused for a format whose service makes the secret.
 */
export function rotatePluginWebhookSecret(
  pluginId: string,
  name: string,
  ownerUserId: string | null,
  publisher: PluginWebhookPublisher,
  opts: RotateOptions & { auth?: WebhookFormatId } = {},
): string {
  const auth = opts.auth ?? 'standard';
  const format = formatOrThrow(auth);
  if (!secretSourcesOf(format).includes('generated')) {
    throw new PluginWebhookSecretError(`${format.label} makes its own secret: paste it instead`);
  }
  const secret = format.scheme.kind === 'hmac' && format.scheme.key === 'whsec' ? generateSecret('standard') : generateSecret('github');
  storeSecret(pluginId, name, auth, 'generated', secret, ownerUserId, publisher, opts);
  return secret;
}

/**
 * Stores the secret (or public key) the sending service gave. Same rotation
 * as a generated one. Returns the subscription verify token when the format
 * confirms its subscription by a GET (Meta) — derived, shown once like a
 * secret — and never the value itself.
 */
export function setPluginWebhookSecret(
  pluginId: string,
  name: string,
  ownerUserId: string | null,
  publisher: PluginWebhookPublisher,
  value: string,
  opts: RotateOptions & { auth?: WebhookFormatId } = {},
): { verifyToken: string | null } {
  const auth = opts.auth ?? 'standard';
  const format = formatOrThrow(auth);
  if (!secretSourcesOf(format).includes('provided')) {
    throw new PluginWebhookSecretError(`${format.label}: the secret is generated by ${BRAND.displayName}, it cannot be pasted`);
  }
  const why = invalidSecret(format.scheme, value);
  if (why) throw new PluginWebhookSecretError(`${format.scheme.kind === 'ed25519' ? 'public key' : 'secret'} refused: ${why}`);
  storeSecret(pluginId, name, auth, 'provided', value, ownerUserId, publisher, opts);
  return { verifyToken: format.scheme.kind === 'hmac' && format.scheme.subscribe ? verifyTokenOf(value) : null };
}

/**
 * Forgets every webhook secret of a plugin — its uninstallation. Unlike its
 * settings, a webhook secret is not something a reinstall should find again:
 * a package published later under the same id (another author included) would
 * otherwise receive the calls of the old one's sender, signed by a secret it
 * never saw, as the account that generated it. Returns the names forgotten.
 */
export function purgePluginWebhookSecrets(pluginId: string): string[] {
  const prefix = recordKey(pluginId, '');
  const names: string[] = [];
  for (const { key } of dbApi.pluginKvList(PLUGIN_WEBHOOK_STORE, prefix)) {
    const name = key.slice(prefix.length);
    // `@settings/@acme/x/<name>`: a deeper key belongs to another id, never to this one.
    if (!name || name.includes('/')) continue;
    dbApi.pluginKvDelete(PLUGIN_WEBHOOK_STORE, key);
    names.push(name);
  }
  return names;
}

/** Ends a rotation now. `false` when there was nothing to revoke. */
export function revokePreviousPluginWebhookSecret(pluginId: string, name: string): boolean {
  const record = readRecord(pluginId, name);
  if (!record?.previous) return false;
  writeRecord(pluginId, name, { ...record, previous: null, previousUntil: null });
  return true;
}

