/** Below the app relay's 15 s, so the relay always reads the daemon's answer. */
export const HANDLER_TIMEOUT_MS = 10_000;
/** Largest reply body a handler may return, serialized. */
export const HANDLER_REPLY_LIMIT = 64 * 1024;

type Verified = { id: string; timestampMs: number | null; replayKeys: string[] };

/**
 * One verdict for every format: `standard` keeps the trigger webhooks' own
 * verifier (byte-for-byte what plugins had before formats), the others go
 * through the generic engine. The previous secret is tried only on a bad
 * signature, never to rescue a stale or malformed call.
 */
function verifyCall(format: WebhookFormat, record: WebhookRecord, body: Buffer, headers: Record<string, string>, at: number): Verified | null {
  const usable = record.previous && record.previousUntil !== null && record.previousUntil > at ? record.previous : null;
  if (format.id === 'standard') {
    let verified = verifySignature('standard', record.current, body, headers, at);
    if (!verified.ok && verified.reason === 'bad_signature' && usable) verified = verifySignature('standard', usable, body, headers, at);
    if (!verified.ok) return null;
    return {
      id: headers['webhook-id'] ?? '',
      timestampMs: Number(headers['webhook-timestamp'] ?? 0) * 1000,
      replayKeys: verified.replayKey ? [verified.replayKey] : [],
    };
  }
  let verified = verifyWithScheme(format.scheme, record.current, body, headers, at);
  if (!verified.ok && verified.reason === 'bad_signature' && usable) verified = verifyWithScheme(format.scheme, usable, body, headers, at);
  if (!verified.ok) return null;
  return { id: verified.id, timestampMs: verified.timestampMs, replayKeys: verified.replayKeys };
}

/** The handler's return value as the JSON body of the 200, or why it cannot be. */
function replyBody(value: unknown): string | Error {
  if (value === undefined) return JSON.stringify({ status: 'received' });
  let text: string | undefined;
  try { text = JSON.stringify(value); } catch (err) { return new Error(`reply is not serializable: ${(err as Error).message}`); }
  if (text === undefined) return new Error('reply is not serializable to JSON');
  if (Buffer.byteLength(text) > HANDLER_REPLY_LIMIT) return new Error(`reply larger than ${HANDLER_REPLY_LIMIT} bytes`);
  return text;
}

function param(req: Request, key: string): string {
  const value: unknown = req.params[key];
  return typeof value === 'string' ? value : '';
}

function withTimeout(work: Promise<void>, ms: number): Promise<void> {
  let timer: NodeJS.Timeout | undefined;
  const limit = new Promise<never>((_resolve, reject) => {
    timer = setTimeout(() => reject(new Error(`handler exceeded ${ms} ms`)), ms);
  });
  return Promise.race([work, limit]).finally(() => clearTimeout(timer));
}

/** Deliveries whose handler is running in this process, by scope and key. */
const inFlight = new Set<string>();

export function registerPluginWebhookRoute(router: Router, options: {
  now?: () => number;
  handlerTimeoutMs?: number;
} = {}): void {
  const now = options.now ?? Date.now;
  const timeoutMs = options.handlerTimeoutMs ?? HANDLER_TIMEOUT_MS;
  const allow = rateLimiter(now);
  const unauthorized = (res: Response) => { res.status(401).json({ error: 'authentication failed' }); };
  const tooMany = (res: Response) => { res.setHeader('Retry-After', '60'); res.status(429).json(apiError('rate_limited', 'rate limited')); };

  router.post('/api/plugins/hooks/:plugin/:name', hookFront({
    allow,
    accepts: (req) => PLUGIN_HOOK_SLUG_RE.test(param(req, 'plugin')) && PLUGIN_HOOK_NAME_RE.test(param(req, 'name')),
    unauthorized,
    tooMany,
  }), (req: Request, res: Response) => {
    // Express 4 does not await a handler: anything thrown outside the
    // handler's own try (the database, the vault) must still answer.
    receive(req, res).catch((err: unknown) => {
      console.error(`[plugin-hooks] ${param(req, 'plugin')}/${param(req, 'name')}: ${(err as Error).message}`);
      if (!res.headersSent) res.status(502).json({ status: 'error' });
    });
  });

  async function receive(req: Request, res: Response): Promise<void> {
    const name = param(req, 'name');
    const registration = handlers.get(handlerKey(param(req, 'plugin'), name));
    if (!registration) { unauthorized(res); return; }
    const { pluginId, handler } = registration;
    const where = `[plugin-hooks] ${pluginId}/${name}`;
    const record = recordFor(registration, name, where);
    if (!record) { unauthorized(res); return; }
    const format = formatOrThrow(registration.auth);

    const body = Buffer.isBuffer(req.body) ? req.body : Buffer.alloc(0);
    const headers = flatHeaders(req);
    const at = now();
    const verified = verifyCall(format, record, body, headers, at);
    if (!verified) { unauthorized(res); return; }

    let identity: ReturnType<typeof integrationRequestIdentity>;
    try {
      // A delivery acts for the account that opened the webhook, but nobody is
      // in front of it: unattended, held to a job's spawn approval (TODO #562).
      identity = integrationRequestIdentity(pluginId, record.ownerUserId ?? `plugin:${pluginId}`);
    } catch {
      // The account that opened the webhook is gone or lost the plugin: the
      // handler would act for nobody. Regenerating the secret re-owns it.
      console.warn(`${where}: its owner account can no longer use the plugin`);
      unauthorized(res);
      return;
    }
    if (!allow([{ key: `route:${pluginId}/${name}`, max: DEFAULT_RATE_LIMIT }])) { tooMany(res); return; }

    // A verified handshake (Slack `url_verification`, Discord `PING`) is the
    // service checking the URL: the host answers, the plugin never sees it.
    const handshake = handshakeReply(format.scheme, body);
    if (handshake) { res.status(200).json(handshake); return; }

    const scope = `plugin-hook:${pluginId}/${name}`;
    const keys = verified.replayKeys;
    const flight = keys.map((key) => `${scope}\n${key}`);
    if (!claimDelivery(scope, keys, at)) {
      // A retry while the first call still runs must not get a 2xx: if that
      // call then fails, the sender would never send the delivery again.
      if (flight.some((key) => inFlight.has(key))) {
        res.setHeader('Retry-After', '5');
        res.status(409).json({ status: 'in_progress' });
        return;
      }
      res.status(200).json({ status: 'duplicate' });
      return;
    }
    for (const key of flight) inFlight.add(key);

    const visible = publicHeaders(headers);
    for (const proof of proofHeaders(format.scheme)) delete visible[proof];
    const text = body.toString('utf8');
    const request: PluginWebhookRequest = Object.freeze({
      name,
      id: verified.id,
      timestamp: verified.timestampMs ?? at,
      headers: Object.freeze(visible),
      text,
      json: <T = unknown>() => JSON.parse(text) as T,
    });
    try {
      let result: unknown;
      await withTimeout(Promise.resolve().then(() => runPluginRequest(identity, () =>
        withTodoOrigin({ kind: 'plugin', id: pluginId }, () => handler(request)))).then((value) => { result = value; }), timeoutMs);
      const reply = replyBody(result);
      if (reply instanceof Error) throw reply;
      // The host sets the type: a plugin cannot answer HTML on a public URL.
      res.status(200).type('application/json').send(reply);
    } catch (err) {
      // Released so the sender's retry runs the handler again: handlers must
      // be idempotent on `request.id`, a timed-out one may still finish.
      releaseDelivery(scope, keys);
      console.error(`[plugin:${pluginId}] webhook \`${name}\` handler failed:`, (err as Error).message);
      // 502 so the sender retries; the detail stays in the daemon log.
      res.status(502).json({ status: 'error' });
    } finally {
      for (const key of flight) inFlight.delete(key);
    }
  }

  /**
   * Subscription check by GET (Meta's `hub.challenge`): answered by the host
   * alone, only with the exact verify token; anything else is the same 401
   * as a forged POST. No plugin code runs, nothing is claimed.
   */
  router.get('/api/plugins/hooks/:plugin/:name', (req: Request, res: Response) => {
    try {
      if (!PLUGIN_HOOK_SLUG_RE.test(param(req, 'plugin')) || !PLUGIN_HOOK_NAME_RE.test(param(req, 'name'))) { unauthorized(res); return; }
      if (!allow([{ key: `subscribe-ip:${req.socket.remoteAddress ?? 'unknown'}`, max: SUBSCRIBE_IP_RATE_LIMIT }])) { tooMany(res); return; }
      const name = param(req, 'name');
      const registration = handlers.get(handlerKey(param(req, 'plugin'), name));
      if (!registration) { unauthorized(res); return; }
      const format = formatOrThrow(registration.auth);
      const record = recordFor(registration, name, `[plugin-hooks] ${registration.pluginId}/${name}`);
      if (!record || format.scheme.kind !== 'hmac' || !format.scheme.subscribe) { unauthorized(res); return; }
      const at = now();
      const secrets = record.previous && record.previousUntil !== null && record.previousUntil > at
        ? [record.current, record.previous] : [record.current];
      const query = new URL(req.originalUrl, 'http://hook.invalid').searchParams;
      const challenge = subscribeChallenge(format.scheme, secrets, query);
      if (challenge === null) { unauthorized(res); return; }
      res.setHeader('X-Content-Type-Options', 'nosniff');
      res.setHeader('Cache-Control', 'no-store');
      res.status(200).type('text/plain').send(challenge);
    } catch (err) {
      console.error(`[plugin-hooks] subscription check failed: ${(err as Error).message}`);
      if (!res.headersSent) unauthorized(res);
    }
  });
}

/** Per source IP for the subscription GET: a handful per dashboard save. */
const SUBSCRIBE_IP_RATE_LIMIT = 30;

/**
 * The record that verifies calls for this registration, `null` when there is
 * none, when the vault cannot open it, when it was made for another format
 * (the plugin changed its manifest) or for another package (the plugin was
 * removed without `rooks plugin remove` and something else took its id): a
 * superadmin must set a new secret.
 */
function recordFor(registration: Registration, name: string, where: string): WebhookRecord | null {
  let record: WebhookRecord | null;
  try { record = readRecord(registration.pluginId, name); } catch (err) {
    // The vault's own message names no value.
    console.warn(`${where}: secret unreadable — ${(err as Error).message}`);
    return null;
  }
  const stale = record ? staleReason(record, registration.auth, registration.publisher) : null;
  if (record && stale === 'format') {
    console.warn(`${where}: its secret was made for \`${record.scheme}\`, the plugin now declares \`${registration.auth}\` — set a new secret`);
    return null;
  }
  if (record && stale === 'publisher') {
    const was = record.publisher;
    const now = registration.publisher;
    console.warn(`${where}: its secret was set for package \`${was?.pkg}\` (${was?.trust}), the plugin loaded is \`${now?.pkg ?? 'unknown'}\` (${now?.trust ?? 'unknown'}) — set a new secret`);
    return null;
  }
  // The vault was locked when the signed release registered: bind it now.
  if (record?.publisher && registration.publisher && signsUnsignedPublisher(record.publisher, registration.publisher)) {
    adoptLegacyRecord(registration.pluginId, name, registration.publisher);
  }
  return record;
}
